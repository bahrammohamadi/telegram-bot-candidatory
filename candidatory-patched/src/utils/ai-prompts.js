// هر تابع یک { system, prompt } برمی‌گرداند که به generateAI داده می‌شود.
// خروجی AI باید «متن آماده‌ی استفاده» باشد، نه توضیح اضافه.
// ═══════════════════════════════════════════════════════════════

// system message مشترک: نقش دستیار کمپین انتخاباتی ایرانی
const BASE_SYSTEM =
  "تو یک متخصص ارشد ارتباطات سیاسی و کمپین انتخاباتی در ایران هستی. " +
  "متن‌هایی روان، فارسیِ معیار، محترمانه، تأثیرگذار و متناسب با فرهنگ ایرانی می‌نویسی. " +
  "از کلیشه و اغراق پرهیز کن. خروجی باید مستقیماً قابل استفاده باشد؛ " +
  "هیچ توضیح اضافه، عنوان «در اینجا متن شما:» یا علامت نقل‌قول دور کل متن نگذار. " +
  "قوانین انتخاباتی و اخلاق حرفه‌ای را رعایت کن و از وعده‌های غیرواقعی یا توهین به رقبا خودداری کن.";

// خلاصه‌ی پروفایل کاندیدا برای شخصی‌سازی
function profileBrief(profile = {}) {
  const p = profile || {};
  const parts = [];
  if (p.fullName) parts.push(`نام: ${p.fullName}`);
  if (p.electionType) parts.push(`نوع انتخابات: ${p.electionType}`);
  if (p.constituency) parts.push(`حوزه: ${p.constituency}`);
  if (p.occupation) parts.push(`شغل: ${p.occupation}`);
  return parts.length ? `\nمشخصات کاندیدا:\n- ${parts.join("\n- ")}\n` : "";
}

// نگاشت ساده‌ی id گزینه‌ها به برچسب فارسی (در صورت نیاز)
function val(x, fallback = "") {
  if (x == null) return fallback;
  if (typeof x === "object") return x.label || x.id || fallback;
  return String(x);
}

// ───────────────────────────────────────────────────────────────
// محتوا: پست شبکه‌ی اجتماعی
// ───────────────────────────────────────────────────────────────
function postPrompt(a = {}, profile = {}) {
  const platform = val(a.platform, "همه پلتفرم‌ها");
  const tone = val(a.tone, "صمیمی");
  const cta = val(a.cta, "اشتراک‌گذاری");
  const topic = a.topic || "موضوع کمپین";
  const tags = (a.hashtags && a.hashtags !== "-") ? a.hashtags : "";

  return {
    system: BASE_SYSTEM,
    prompt:
      `یک پست شبکه‌ی اجتماعی برای کمپین انتخاباتی بنویس.\n` +
      profileBrief(profile) +
      `\nمشخصات پست:\n` +
      `- پلتفرم: ${platform}\n` +
      `- لحن: ${tone}\n` +
      `- موضوع: ${topic}\n` +
      `- دعوت به اقدام (CTA): ${cta}\n` +
      (tags ? `- هشتگ‌های پیشنهادی: ${tags}\n` : "") +
      `\nراهنما: متن جذاب، کوتاه تا متوسط، با شکست خط مناسب و چند ایموجی هدفمند. ` +
      `در پایان CTA و در صورت وجود، هشتگ‌ها را اضافه کن.`,
  };
}

// ───────────────────────────────────────────────────────────────
// محتوا: متن سخنرانی
// ───────────────────────────────────────────────────────────────
function speechPrompt(a = {}, profile = {}) {
  const kind = val(a.kind, "گردهمایی");
  const audience = val(a.audience, "عموم مردم");
  const duration = val(a.duration, "متوسط");
  const topic = a.topic || a.theme || "اهداف کمپین";

  return {
    system: BASE_SYSTEM,
    prompt:
      `یک متن سخنرانی انتخاباتی بنویس.\n` +
      profileBrief(profile) +
      `\nمشخصات سخنرانی:\n` +
      `- نوع: ${kind}\n` +
      `- مخاطب: ${audience}\n` +
      `- طول تقریبی: ${duration}\n` +
      `- محور اصلی: ${topic}\n` +
      `\nساختار: شروع گیرا، بدنه با ۲ تا ۳ محور مشخص و ملموس برای حوزه، و پایان الهام‌بخش با دعوت به مشارکت. ` +
      `لحن گرم و قابل ارائه‌ی شفاهی باشد.`,
  };
}

// ───────────────────────────────────────────────────────────────
// محتوا: شعار انتخاباتی (چند گزینه)
// ───────────────────────────────────────────────────────────────
function sloganPrompt(a = {}, profile = {}) {
  const theme = a.theme || a.topic || "تغییر و خدمت";
  const tone = val(a.tone, "امیدبخش");
  return {
    system: BASE_SYSTEM,
    prompt:
      `۶ شعار انتخاباتی کوتاه، خوش‌آهنگ و به‌یادماندنی به فارسی پیشنهاد بده.\n` +
      profileBrief(profile) +
      `\n- محور: ${theme}\n- حال‌وهوا: ${tone}\n` +
      `\nهر شعار را در یک خط جداگانه و با شماره بنویس. از قافیه یا ریتم استفاده کن. حداکثر ۷ کلمه برای هر شعار.`,
  };
}

