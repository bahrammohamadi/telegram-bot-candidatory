// ───────────────────────────────────────────────────────────────
// پاسخ به انتقاد / شایعه (مدیریت بحران)
// ───────────────────────────────────────────────────────────────
function responsePrompt({ kind = "criticism", text = "", profile = {} } = {}) {
  const label = kind === "rumor" ? "شایعه" : "انتقاد";
  return {
    system: BASE_SYSTEM,
    prompt:
      `یک پاسخ حرفه‌ای، آرام و قانع‌کننده به ${label} زیر بنویس که برای انتشار عمومی مناسب باشد.\n` +
      profileBrief(profile) +
      `\nمتن ${label}:\n«${text}»\n` +
      `\nراهنما: بدون عصبانیت و بدون توهین متقابل. ابتدا فضا را آرام کن، سپس با منطق و شفافیت پاسخ بده و در پایان به ارزش‌های مثبت کمپین برگرد.`,
  };
}

