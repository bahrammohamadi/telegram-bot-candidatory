// ───────────────────────────────────────────────────────────────
// روتر یکپارچه callback های contact:*
// ───────────────────────────────────────────────────────────────
async function handleContactCallback(ctx) {
  const data = ctx.callbackQuery?.data || "";
  const parts = data.split(":");

  if (parts[0] !== "contact") return;

  try {
    const action = parts[1];

    if (action === "about")   return handleAboutUs(ctx);
    if (action === "contact") return handleContactUs(ctx);
    if (action === "samples") return handleSampleReports(ctx);
    if (action === "faq")     return handleFAQMenu(ctx);
    if (action === "faqi")    return handleFAQItem(ctx, parts[2]);
    if (action === "privacy") return handlePrivacy(ctx);

    await ctx.answerCallbackQuery({ text: "عملیات نامعتبر", show_alert: false });
  } catch (e) {
    console.error("[contact] callback error:", e);
    try {
      await ctx.answerCallbackQuery({ text: "خطا در پردازش", show_alert: true });
    } catch {}
  }
}

