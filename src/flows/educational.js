function findCard(cardId) {
  return EDU_CARDS.find((c) => c.id === cardId) || null;
}

function findTab(tabId) {
  return EDU_TABS.find((t) => t.id === tabId) || null;
}

function getCardIndex(cardId) {
  return EDU_CARDS.findIndex((c) => c.id === cardId);
}

/** ساخت کیبورد لیست کارت‌ها (با صفحه‌بندی) */
function buildCardsListKB(page = 0) {
  const PER_PAGE = 6;
  const totalPages = Math.ceil(EDU_CARDS.length / PER_PAGE);
  const safePage = Math.max(0, Math.min(page, totalPages - 1));
  const start = safePage * PER_PAGE;
  const slice = EDU_CARDS.slice(start, start + PER_PAGE);

  const kb = new InlineKeyboard();
  slice.forEach((card, i) => {
    const globalIndex = start + i + 1;
    kb.text(`${card.emoji} ${globalIndex}. ${card.title}`, `edu:card:${card.id}`).row();
  });

  // ناوبری صفحه
  if (totalPages > 1) {
    if (safePage > 0) {
      kb.text("⬅️ قبلی", `edu:page:${safePage - 1}`);
    }
    kb.text(`📖 ${safePage + 1}/${totalPages}`, "edu:noop");
    if (safePage < totalPages - 1) {
      kb.text("بعدی ➡️", `edu:page:${safePage + 1}`);
    }
    kb.row();
  }

  kb.text("🏠 منوی اصلی", "menu");
  return kb;
}

/** ساخت کیبورد تب‌های یک کارت */
function buildTabsKB(cardId) {
  const kb = new InlineKeyboard();
  EDU_TABS.forEach((tab, i) => {
    kb.text(`${tab.emoji} ${tab.label}`, `edu:tab:${cardId}:${tab.id}`);
    if ((i + 1) % 2 === 0) kb.row();
  });
  if (EDU_TABS.length % 2 !== 0) kb.row();
  kb.text("📚 سایر کارت‌ها", "edu:list").row();
  kb.text("🏠 منوی اصلی", "menu");
  return kb;
}

/** ساخت کیبورد بعد از مشاهده‌ی تب */
function buildAfterTabKB(cardId, currentTabId) {
  const kb = new InlineKeyboard();

  // سایر تب‌ها (به جز فعلی) — حداکثر ۴ تا برای شلوغ نشدن
  const others = EDU_TABS.filter((t) => t.id !== currentTabId).slice(0, 4);
  others.forEach((t, i) => {
    kb.text(`${t.emoji} ${t.label}`, `edu:tab:${cardId}:${t.id}`);
    if ((i + 1) % 2 === 0) kb.row();
  });
  if (others.length % 2 !== 0) kb.row();

  // ناوبری بین کارت‌ها
  const idx = getCardIndex(cardId);
  if (idx > 0) {
    kb.text("⬅️ کارت قبلی", `edu:card:${EDU_CARDS[idx - 1].id}`);
  }
  if (idx < EDU_CARDS.length - 1) {
    kb.text("کارت بعدی ➡️", `edu:card:${EDU_CARDS[idx + 1].id}`);
  }
  kb.row();

  kb.text("📚 لیست کارت‌ها", "edu:list").row();
  kb.text("🏠 منوی اصلی", "menu");
  return kb;
}

/** قالب‌بندی محتوای یک تب */
function formatTabContent(card, tab) {
  const data = card[tab.field];
  const header = `${tab.emoji} *${tab.label} — ${card.emoji} ${card.title}*\n━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n`;

  if (!data) {
    return header + "_محتوای این بخش هنوز آماده نشده است._";
  }

  if (tab.type === "list" && Array.isArray(data)) {
    return header + data.join("\n\n");
  }

  return header + String(data);
}

