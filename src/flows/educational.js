// ─── ساخت کیبورد تب‌های یک کارت ───
function cardTabsKB(cardId, currentView) {
  const kb = new InlineKeyboard();

  // تب‌ها در یک ردیف
  for (const view of VIEWS) {
    const isActive = view === currentView;
    const label = isActive ? `▶ ${VIEW_LABELS[view]}` : VIEW_LABELS[view];
    kb.text(label, `eduv:${cardId}:${view}`);
  }
  kb.row();

  // ناوبری بین کارت‌ها
  if (cardId > 0) {
    kb.text("⬅️ قبلی", `edu:${cardId - 1}`);
  }
  kb.text("📚 لیست", "edu_list");
  if (cardId < CARDS.length - 1) {
    kb.text("بعدی ➡️", `edu:${cardId + 1}`);
  }
  kb.row();

  kb.text("🔙 منو", "menu").row();

  return kb;
}

// ─── ساخت متن کارت بر اساس تب ───
function buildCardText(card, view) {
  let t = `${card.emoji} *${card.title}*\n`;
  t += "━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n";

  switch (view) {
    case "summary":
      t += card.content;
      break;

    case "keypoints":
      t += "🎯 *نکات کلیدی*\n\n";
      card.keyPoints.forEach((p, i) => {
        t += `${i + 1}. ${p}\n\n`;
      });
      break;

    case "mistakes":
      t += "❌ *اشتباهات رایج*\n\n";
      card.commonMistakes.forEach((m, i) => {
        t += `${i + 1}. ${m}\n\n`;
      });
      break;

    case "exercises":
      t += "📝 *تمرین‌های عملی*\n\n";
      card.practicalExercises.forEach((e, i) => {
        t += `${i + 1}. ${e}\n\n`;
      });
      break;

    case "tips":
      t += "💡 *نکات طلایی*\n\n";
      card.proTips.forEach((tip, i) => {
        t += `${i + 1}. ${tip}\n\n`;
      });
      break;

    default:
      t += card.content;
  }

  t += `\n─── کارت ${card.id + 1} از ${CARDS.length} ───`;
  return t;
}

