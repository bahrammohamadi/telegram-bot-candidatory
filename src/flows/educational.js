// هندلر ۳: نمایش یک تب از کارت (با چک دسترسی)
// ───────────────────────────────────────────────────────────────
async function handleEducationView(ctx, cardId, tabId) {
  const card = findCard(cardId);
  const tab = findTab(tabId);

  if (!card) {
    await ctx.answerCallbackQuery({ text: "کارت یافت نشد", show_alert: true });
    return;
  }
  if (!tab) {
    await ctx.answerCallbackQuery({ text: "بخش یافت نشد", show_alert: true });
    return;
  }

  // چک دسترسی به این تب
  const access = await requireAccess(ctx, tab.feature);
  if (!access) return;

  const text = formatTabContent(card, tab);
  const kb = buildAfterTabKB(cardId, tabId);

  // مدیریت پیام‌های بلند (محدودیت ۴۰۹۶ کاراکتر تلگرام)
  if (text.length > 3900) {
    const part1 = text.slice(0, 3900);
    const part2 = text.slice(3900);

    if (ctx.callbackQuery) {
      try {
        await ctx.editMessageText(part1, { parse_mode: "Markdown" });
      } catch {
        await ctx.reply(part1, { parse_mode: "Markdown" });
      }
      await ctx.answerCallbackQuery();
    } else {
      await ctx.reply(part1, { parse_mode: "Markdown" });
    }
    await ctx.reply(part2, { parse_mode: "Markdown", reply_markup: kb });
    return;
  }

  if (ctx.callbackQuery) {
    try {
      await ctx.editMessageText(text, { parse_mode: "Markdown", reply_markup: kb });
    } catch {
      await ctx.reply(text, { parse_mode: "Markdown", reply_markup: kb });
    }
    await ctx.answerCallbackQuery();
  } else {
    await ctx.reply(text, { parse_mode: "Markdown", reply_markup: kb });
  }
}

