// ✅ تابع ۱: نمایش لیست کارت‌های آموزشی
// ═══════════════════════════════════════════════════════════════
async function handleShowEducationList(ctx) {
  let text = "📚 *آموزش جامع کاندیداتوری*\n";
  text += "━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n";
  text += "کارت‌های آموزشی زیر را انتخاب کنید:\n\n";

  const kb = new InlineKeyboard();

  EDUCATION_CARDS.forEach((card, idx) => {
    text += `${card.emoji} *${card.title}*\n${card.summary}\n\n`;
    kb.text(`${card.emoji} ${card.title}`, `edu_card:${card.id}`);
    if ((idx + 1) % 2 === 0) kb.row();
  });

  kb.row().text("🏠 منو", "menu");

  if (ctx.callbackQuery) {
    try {
      await ctx.editMessageText(text, { parse_mode: "Markdown", reply_markup: kb });
    } catch {
      await ctx.reply(text, { parse_mode: "Markdown", reply_markup: kb });
    }
    await ctx.answerCallbackQuery();
  } else {
    await ctx.reply(text, { parse_mode: "Markdown", reply_markup: kb });
  }
}

